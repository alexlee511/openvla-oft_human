def get_humanized_initial_arm_joint_pose(suite_name: str, task_stem: str, episode_idx: int):
    suite_poses = HUMANIZED_INITIAL_ARM_JOINTS_BY_SUITE.get(suite_name)
    if suite_poses is None:
        return None
    poses = suite_poses.get(task_stem)
    if poses is None or episode_idx < 0 or episode_idx >= len(poses):
        return None
    return np.asarray(poses[episode_idx], dtype=np.float32)
